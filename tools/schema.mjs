// The database as it is after every migration, in one readable file: supabase/schema.sql. Migrations stay the only
// thing ever applied; this is how to see what a function, a policy or a grant says now without reading 140 files.
// Written from the local stack (`npm run db:start`), so run it after adding a migration and applying it:
//
//   node tools/schema.mjs           write supabase/schema.sql
//   node tools/schema.mjs --check   exit 1 when the file is not what the database holds (CI, on a fresh stack)
import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const file = join(dirname(fileURLToPath(import.meta.url)), "..", "supabase", "schema.sql");
const container = process.env.DB_CONTAINER || "supabase_db_longtable";
const dump = execFileSync("docker", ["exec", container, "pg_dump", "-U", "postgres", "-d", "postgres", "--schema-only", "--schema=public", "--no-owner"],
  { encoding: "utf8", maxBuffer: 64 * 1024 * 1024 });
// What changes from one dump to the next without the schema changing: pg_dump's random restrict key, its version, and the
// line endings a migration happened to be applied with.
const schema = dump.replace(/\r\n/g, "\n").split("\n").filter((l) => !/^\\(un)?restrict /.test(l) && !/^-- Dumped (from|by) /.test(l)).join("\n").replace(/\n{3,}/g, "\n\n");
const head = "-- Generated by tools/schema.mjs from the migrations. Never edit it: change the database with a new migration.\n";

if (process.argv.includes("--check")) {
  const kept = existsSync(file) ? readFileSync(file, "utf8").replace(/\r\n/g, "\n") : "";
  if (kept !== head + schema) {
    console.error("supabase/schema.sql is not what the migrations make. Run `node tools/schema.mjs` and commit it.");
    process.exit(1);
  }
  console.log("supabase/schema.sql matches the database");
} else {
  writeFileSync(file, head + schema);
  console.log(`wrote supabase/schema.sql (${Math.round((head + schema).length / 1024)} KB)`);
}
